#!/usr/bin/env python3
"""Sync or verify the pinned Devin's Badges SVG catalog (standard library only)."""

import argparse
import base64
import gzip
import hashlib
import html
import io
import json
import re
import tarfile
import urllib.request
import xml.etree.ElementTree as ET
from pathlib import Path

VERSION = "3.3.1"
STYLES = ("cozy", "compact", "cozy-minimal", "compact-minimal")
ROOT = Path(__file__).resolve().parents[1] / "assets" / "devins-badges"
PACKAGE = "https://registry.npmjs.org/@intergrav%2fdevins-badges/"
DOCS = "https://intergrav.github.io/devins-badges-docs/badges/"


def fetch(url):
    with urllib.request.urlopen(url, timeout=30) as response:
        return response.read()


def catalog():
    release = json.loads(fetch(PACKAGE + VERSION))
    archive = fetch(release["dist"]["tarball"])
    integrity = "sha512-" + base64.b64encode(hashlib.sha512(archive).digest()).decode()
    if integrity != release["dist"]["integrity"]:
        raise ValueError("Upstream package integrity check failed")
    with tarfile.open(fileobj=io.BytesIO(archive)) as package:
        for item in package:
            match = re.fullmatch(
                r"package/assets/((?:assets/)?(cozy|compact|cozy-minimal|compact-minimal)/"
                r"([\w-]+/[\w-]+)_vector\.svg)", item.name
            )
            if match and item.isfile():
                path, style, badge = match.groups()
                original = package.extractfile(item).read()
                svg = ET.fromstring(original)
                if svg.tag != "{http://www.w3.org/2000/svg}svg":
                    raise ValueError(f"Malformed badge: {path}")
                yield badge, style, path, original


def build():
    files = {}
    entries = {}
    by_style = {style: {} for style in STYLES}
    files["CC0-1.0.txt"] = fetch(
        "https://raw.githubusercontent.com/intergrav/devins-badges/"
        "0a3449fd26bf1375d2c5c26f096c8f30aa358766/LICENSE"
    )
    for badge, style, path, original in catalog():
        if style in entries.setdefault(badge, {}):
            raise ValueError(f"Duplicate badge ID: {badge} ({style})")
        entries[badge][style] = path
        files[path] = original
        by_style[style][badge] = original.decode("utf-8")

    names = {}
    for style in STYLES:
        page = html.unescape(fetch(DOCS + style + "/").decode())
        documented = set(re.findall(r"/assets/([\w/-]+_vector\.svg)", page))
        assert documented, f"No SVG references found in {style} documentation"
        assert documented <= files.keys(), documented - files.keys()
        for name, section in re.findall(r"<h4[^>]*>(.*?)</h4>(.*?)(?=<h[34]|\Z)", page, re.S):
            match = re.search(rf"/assets/{style}/([\w-]+/[\w-]+)_vector\.svg", section)
            if match:
                names.setdefault(match[1], re.sub(r"<[^>]+>", "", name).strip())

    metadata = {}
    for badge, styles in sorted(entries.items()):
        assert styles.keys() == by_style.keys(), (badge, styles)
        slug = badge.split("/")[1]
        metadata[badge] = {
            "name": names.get(badge) or slug.replace("-", " ").title(),
            "paths": {style: styles[style] for style in STYLES},
        }
    files["catalog.js"] = (
        f"// Generated by scripts/sync-official-badges.py from Devin's Badges {VERSION}.\n"
        "const DEVINS_BADGES = " + json.dumps(metadata, indent=2, ensure_ascii=False) + ";\n"
    ).encode()
    for style, badges in by_style.items():
        # Files opened directly in a browser cannot fetch sibling SVGs. Load one
        # compressed script per requested style, with the original text intact.
        content = json.dumps(badges, ensure_ascii=False, separators=(",", ":"), sort_keys=True)
        packed = base64.b64encode(gzip.compress(content.encode(), mtime=0)).decode()
        files[f"{style}.js"] = f"registerOfficialBadgePack({json.dumps(style)},\n'{packed}');\n".encode()

    return files, len(entries)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="compare local files with the upstream package")
    args = parser.parse_args()
    expected, count = build()
    if args.check:
        actual = {str(path.relative_to(ROOT)) for path in ROOT.rglob("*") if path.is_file()}
        mismatches = sorted(actual ^ expected.keys())
        mismatches.extend(path for path in actual & expected.keys() if (ROOT / path).read_bytes() != expected[path])
        if mismatches:
            parser.exit(1, "Catalog differences:\n" + "\n".join(sorted(set(mismatches))) + "\n")
    else:
        for path, content in expected.items():
            target = ROOT / path
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(content)
    print(f"{'Verified' if args.check else 'Synced'} {count} badges and {count * len(STYLES)} original SVGs (v{VERSION}).")


if __name__ == "__main__":
    main()
